"""Offline real-record validation. Uses explicit frozen FX; never downloads data.

Run from the checkout with --cache-dir, --fx-json and --output-dir. FX JSON maps
FROM/TO to a positive rate and contains an optional _provenance record.
No golden expectation is regenerated by this command.
"""
from pathlib import Path
import argparse,hashlib,json,math,pickle,sys,tomllib
from datetime import date
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
import pandas as pd
from screener import metrics,scoring,valuation as V
from screener.__main__ import load_class_overrides

class FrozenFX:
    def __init__(self,rates):self.rates=rates
    def rate(self,a,b):
        if a==b:return 1.0
        if a+'/'+b in self.rates:return self.rates[a+'/'+b]
        if b+'/'+a in self.rates:return 1/self.rates[b+'/'+a]
        raise ValueError(f"missing explicit frozen FX {a}/{b}")

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    for key in ('cache-dir','fx-json','output-dir'):parser.add_argument('--'+key,required=True,type=Path)
    parser.add_argument('--valuation-date',required=True,type=date.fromisoformat,help='Explicit replay date YYYY-MM-DD; does not remove look-ahead from later raw snapshots')
    args=parser.parse_args();root=Path(__file__).resolve().parents[1]
    cfg=tomllib.loads((root/'config.toml').read_text(encoding='utf-8'))
    overrides=load_class_overrides(root/cfg['inputs']['classification_overrides'])
    fxdata=json.loads(args.fx_json.read_text(encoding='utf-8'));fx=FrozenFX(fxdata)
    rows=[];errors=[];hashes={};invariants=0
    for path in sorted(args.cache_dir.glob('*.pkl')):
        raw=path.read_bytes();hashes[path.name]=hashlib.sha256(raw).hexdigest()
        data=pickle.loads(raw) # own local Yahoo cache only
        data={**data,"source_snapshot":str(path.resolve()),"source_sha256":hashes[path.name]}
        try:
            m=metrics.compute(data,None,fx,cfg,overrides.get(data['symbol']),valuation_date=args.valuation_date)
            assert 'assumed debt-free' not in m.get('flags','')
            if 'entry_score' in m:
                assert math.isfinite(m['entry_ceiling']) and m['entry_ceiling']>0
                ds,terminal=V.distributions(m['base_earnings'],m['est_growth'],m['terminal_growth'],
                                            cfg['valuation']['years'],m['return_on_capital'],m['terminal_return'])
                assert min(ds+[terminal])>=0
                expected=V.discount(ds,terminal,m['hurdle'],m['terminal_growth'])
                assert expected>0
                if m.get('implied_growth') is not None:
                    assert m['implied_growth_status']=='solved'
                invariants+=1
            rows.append(m)
        except Exception as exc:
            errors.append({'symbol':data['symbol'],'error':repr(exc)})
    frame=scoring.score(pd.DataFrame(rows),cfg)
    args.output_dir.mkdir(parents=True,exist_ok=True)
    frame.to_csv(args.output_dir/'results.csv',index=False)
    summary={'valuation_date':str(args.valuation_date),'records':len(hashes),'successful_computations':len(rows),'funded_path_invariant_checks':invariants,
             'statuses':frame['status'].value_counts().to_dict(),'errors':errors,'source_hashes':hashes,
             'fx_provenance':fxdata.get('_provenance'),'config_sha256':hashlib.sha256((root/'config.toml').read_bytes()).hexdigest(),
             'limits':'Cached record replay with explicit frozen FX; no current-price or issuer-filing verification and no return backtest.'}
    (args.output_dir/'validation.json').write_text(json.dumps(summary,indent=2),encoding='utf-8')
    print(json.dumps({k:v for k,v in summary.items() if k not in ('source_hashes','fx_provenance')},indent=2))
    return bool(errors)

if __name__=='__main__':raise SystemExit(main())
